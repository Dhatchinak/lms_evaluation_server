import 'dotenv/config';
import {existsSync} from 'node:fs';
import {resolve} from 'node:path';
const problems:string[]=[];
const envFile=resolve(process.cwd(),'.env');
console.log('BHC LMS Evaluation backend configuration check');
console.log('Current folder:',process.cwd());
console.log('server/.env present:',existsSync(envFile)?'YES':'NO');
if(!existsSync(envFile))problems.push('Copy .env.example to .env in the server folder.');
const uri=process.env.MONGO_URI||'';
console.log('MongoDB URI configured:',uri&&!uri.includes('USER:PASSWORD')?'YES':'NO');
if(!uri||uri.includes('USER:PASSWORD'))problems.push('Set a valid MONGO_URI in server/.env (do not publish it).');
console.log('Session secret valid:',(process.env.SESSION_SECRET||'').length>=32?'YES':'NO');
if((process.env.SESSION_SECRET||'').length<32)problems.push('Set SESSION_SECRET to at least 32 random characters.');
console.log('DEMO_MODE:',process.env.DEMO_MODE||'(unset; defaults to false)');
if(process.env.DEMO_MODE==='true')problems.push('Set DEMO_MODE=false.');
console.log('ERP departments URL:',process.env.ERP_DEPARTMENTS_URL||'(default URL)');
console.log('Server port:',process.env.PORT||'4000');
if(problems.length){for(const issue of problems)console.error('FIX:',issue);process.exitCode=1;}else console.log('Configuration values are present. Run npm run dev, then test /api/health; this does not confirm connectivity.');
